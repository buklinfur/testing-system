#!/usr/bin/env python3
"""Write docs/openapi-admin.json and docs/openapi-student.json: the OpenAPI of what each web UI calls.

openapi-admin.json: /api/admin and /api/auth; openapi-student.json: the student API (/api/contests,
/api/submissions, /api/load) and /api/auth. The public app never serves its OpenAPI over the network (MODULE_4A 5.7,
openapi_url=None); these files in the repository are the published description. tests/test_openapi_units.py fails
when one differs from the app: after changing an endpoint run

    python tools/gen-openapi.py            # rewrite both files
    python tools/gen-openapi.py --check    # exit 1 if either is out of date
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path[:0] = [str(ROOT), str(ROOT / "backend")]
AUTH = ("/api/auth/",)
# file -> (title, path prefixes); a prefix ends with "/" or is a whole path, so /api/admin never takes /api/adminx
TARGETS = {
    "admin": (ROOT / "docs" / "openapi-admin.json", "judge: admin and auth API", ("/api/admin/",) + AUTH),
    "student": (ROOT / "docs" / "openapi-student.json", "judge: student and auth API",
                ("/api/contests", "/api/submissions", "/api/load") + AUTH),
}
OUT = TARGETS["admin"][0]  # the admin file (kept for callers of module 4a)


def _wanted(path: str, prefixes: tuple) -> bool:
    return any(path.startswith(p) if p.endswith("/") else path == p or path.startswith(p + "/") for p in prefixes)


def build(target: str = "admin") -> dict:
    """The OpenAPI document of the public app, limited to the prefixes of `target`, with stable key order. Schemas
    of the components are kept only when a path of the document refers to them."""
    from cryptography.fernet import Fernet

    from app.public_main import create_public_app
    from app.settings import AuthSettings, Settings

    settings = Settings(public_origin="https://judge.example.ru", auth=AuthSettings(secret_key=Fernet.generate_key().decode()))
    app = create_public_app(settings, session_factory=lambda: None)
    doc = app.openapi()
    _out, title, prefixes = TARGETS[target]
    if target == "admin":
        doc["info"] = {"title": title, "version": "4a.3",
                       "description": "Generated by tools/gen-openapi.py; the human description is docs/ADMIN_API.md."}
    else:
        doc["info"] = {"title": title, "version": "4b.1",
                       "description": "Generated by tools/gen-openapi.py; the human description is docs/STUDENT_API.md."}
    doc["paths"] = {path: ops for path, ops in doc["paths"].items() if _wanted(path, prefixes)}
    _prune(doc)  # each file only the schemas its paths use (the admin file: all it had before 4b.1)
    return doc


def _prune(doc: dict) -> None:
    """Drop the component schemas no path of the document reaches (no admin body in the student file, no student
    body in the admin file)."""
    schemas = doc.get("components", {}).get("schemas", {})
    seen, todo = set(), [doc["paths"]]
    while todo:
        node = todo.pop()
        if isinstance(node, dict):
            ref = node.get("$ref")
            if isinstance(ref, str) and ref.startswith("#/components/schemas/"):
                name = ref.rsplit("/", 1)[-1]
                if name not in seen and name in schemas:
                    seen.add(name)
                    todo.append(schemas[name])
            todo.extend(node.values())
        elif isinstance(node, list):
            todo.extend(node)
    doc["components"]["schemas"] = {k: v for k, v in schemas.items() if k in seen}


def render(doc: dict) -> str:
    return json.dumps(doc, ensure_ascii=False, indent=2, sort_keys=True) + "\n"


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="only compare; exit 1 if the file is out of date")
    args = parser.parse_args(argv)
    stale = 0
    for target, (out, _title, _prefixes) in TARGETS.items():
        text = render(build(target))
        if args.check:
            current = out.read_text(encoding="utf-8") if out.exists() else ""
            if current != text:
                print(f"{out.relative_to(ROOT)} is out of date: run python tools/gen-openapi.py", file=sys.stderr)
                stale += 1
            continue
        out.write_text(text, encoding="utf-8")
        print(f"written {out.relative_to(ROOT)} ({len(json.loads(text)['paths'])} paths)")
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
