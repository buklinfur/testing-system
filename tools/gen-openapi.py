#!/usr/bin/env python3
"""Write docs/openapi-admin.json: the OpenAPI of /api/admin and /api/auth (what the admin web UI calls).

The public app never serves its OpenAPI over the network (MODULE_4A 5.7, openapi_url=None); this file in the
repository is the published description. tests/test_openapi_units.py fails when it differs from the app: after
changing an endpoint run

    python tools/gen-openapi.py            # rewrite the file
    python tools/gen-openapi.py --check    # exit 1 if it is out of date
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path[:0] = [str(ROOT), str(ROOT / "backend")]
OUT = ROOT / "docs" / "openapi-admin.json"
PREFIXES = ("/api/admin", "/api/auth")


def build() -> dict:
    """The OpenAPI document of the public app, limited to PREFIXES, with stable key order."""
    from cryptography.fernet import Fernet

    from app.public_main import create_public_app
    from app.settings import AuthSettings, Settings

    settings = Settings(public_origin="https://judge.example.ru", auth=AuthSettings(secret_key=Fernet.generate_key().decode()))
    app = create_public_app(settings, session_factory=lambda: None)
    doc = app.openapi()
    doc["info"] = {"title": "judge: admin and auth API", "version": "4a.3",
                   "description": "Generated by tools/gen-openapi.py; the human description is docs/ADMIN_API.md."}
    doc["paths"] = {path: ops for path, ops in doc["paths"].items() if path.startswith(PREFIXES)}
    return doc


def render(doc: dict) -> str:
    return json.dumps(doc, ensure_ascii=False, indent=2, sort_keys=True) + "\n"


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="only compare; exit 1 if the file is out of date")
    args = parser.parse_args(argv)
    text = render(build())
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT.relative_to(ROOT)} is out of date: run python tools/gen-openapi.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"written {OUT.relative_to(ROOT)} ({len(json.loads(text)['paths'])} paths)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
