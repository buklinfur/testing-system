# --- the grammar of links, a copy of app/materials/links.py at 4v.4 (a unit test compares them)
PREFIX = "памятка"
LABEL_MAX = 200
SLUG_PATTERN = r"[a-z0-9][a-z0-9-]{1,62}"
LINK_RE = re.compile(r"\[\[(?i:" + PREFIX + r"):(" + SLUG_PATTERN + r")(?:\|([^\[\]|\n]+))?\]\]")
CANDIDATE_RE = re.compile(r"\[\[[ \t]*(?i:" + PREFIX + r")[ \t]*:[^\n]*?\]\]")
BAD_LABEL_CATEGORIES = frozenset({"Cc", "Cf", "Cs", "Co", "Cn", "Zl", "Zp"})


def link_slugs(text):
    """The distinct slugs of the links of a text, in order (links.slugs of 4v.4 for one text)."""
    out = {}
    for candidate in CANDIDATE_RE.finditer(text or ""):
        match = LINK_RE.fullmatch(candidate.group(0))
        if match is None:
            continue
        label = match.group(2)
        if label is not None:
            label = label.strip()
            if not label or len(label) > LABEL_MAX or any(unicodedata.category(ch) in BAD_LABEL_CATEGORIES
                                                          for ch in label):
                continue
        out.setdefault(match.group(1), None)
    return list(out)


def backfill(bind) -> int:
    """material_refs for the statements of every problem version and the body of every feed item."""
    rows = []
    for version_id, statements in bind.execute(sa.text("SELECT id, statements FROM problem_versions ORDER BY id")):
        texts = [statements[lang] for lang in sorted(statements or {}) if isinstance(statements[lang], str)]
        slugs = {}
        for text in texts:
            for slug in link_slugs(text):
                slugs.setdefault(slug, None)
        rows += [{"slug": s, "pv": version_id, "fi": None} for s in slugs]
    for item_id, body in bind.execute(sa.text("SELECT id, body_md FROM feed_items ORDER BY id")):
        rows += [{"slug": s, "pv": None, "fi": item_id} for s in link_slugs(body)]
    if rows:
        bind.execute(sa.text("INSERT INTO material_refs (slug, problem_version_id, feed_item_id) "
                             "VALUES (:slug, :pv, :fi)"), rows)
    return len(rows)


